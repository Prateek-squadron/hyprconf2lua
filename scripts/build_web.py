#!/usr/bin/env python3
"""Build web assets by bundling hyprconf2lua package sources into a single JS file for Pyodide."""

from pathlib import Path
import json

ROOT_DIR = Path(__file__).resolve().parent.parent
SRC_DIR = ROOT_DIR / "src" / "hyprconf2lua"
WEB_DIR = ROOT_DIR / "web"


def build_bundle() -> None:
    WEB_DIR.mkdir(parents=True, exist_ok=True)
    bundle = {}

    for py_file in sorted(SRC_DIR.glob("*.py")):
        content = py_file.read_text(encoding="utf-8")
        bundle[py_file.name] = content

    output_file = WEB_DIR / "hyprconf2lua_bundle.js"
    json_data = json.dumps(bundle, indent=2)
    js_content = f"// Auto-generated by scripts/build_web.py - do not edit directly.\nwindow.HYPRCONF2LUA_BUNDLE = {json_data};\n"

    output_file.write_text(js_content, encoding="utf-8")
    size_kb = len(js_content.encode("utf-8")) / 1024
    print(f"Bundled {len(bundle)} files into {output_file.relative_to(ROOT_DIR)} ({size_kb:.1f} KB)")


if __name__ == "__main__":
    build_bundle()
